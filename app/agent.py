import json
from ollama import Client

from app.diagnostics import (
    check_service_health,
    get_recent_logs,
    check_response_time,
)

MODEL = "llama3.1:8b"

TOOLS = {
    "check_service_health": check_service_health,
    "get_recent_logs": get_recent_logs,
    "check_response_time": check_response_time,
}

SYSTEM_PROMPT = """
You are an IT incident investigation assistant investigating simulated incidents.

Rules:
- Use only the provided diagnostic tools.
- Never invent logs, metrics, timestamps, or tool results.
- A log timestamp is not necessarily the incident start time.
- The incident start time is unknown unless explicitly provided.
- Missing response-time data does not mean zero latency.
- Distinguish confirmed evidence from possible causes.
- Never claim that you fixed an incident.
- Never include JSON tool requests in the final report.

Your final report must contain:
1. Incident summary
2. Evidence collected
3. Likely cause
4. Recommended actions
"""


def investigate_incident(scenario: str) -> dict:
    """Investigate a simulated incident using Ollama tool calling."""

    client = Client(host="http://localhost:11434")

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {
            "role": "user",
            "content": (
                f"Investigate the simulated incident scenario: {scenario}. "
                "Use diagnostic tools before writing your report."
            ),
        },
    ]

    executed_tools = []

    for _ in range(5):
        response = client.chat(
            model=MODEL,
            messages=messages,
            tools=list(TOOLS.values()),
        )

        messages.append(response.message)

        if not response.message.tool_calls:
            missing_tools = [
                name for name in TOOLS
                if name not in executed_tools
            ]

            if missing_tools:
                messages.append({
                    "role": "user",
                    "content": (
                        "The investigation is incomplete. "
                        "Call these remaining diagnostic tools: "
                        f"{', '.join(missing_tools)}. "
                        "Do not write the final report yet."
                    ),
                })
                continue

            return {
                "scenario": scenario,
                "tools_used": executed_tools,
                "report": response.message.content,
            }

        for tool_call in response.message.tool_calls:
            function_name = tool_call.function.name

            if function_name not in TOOLS:
                result = {"error": f"Unknown tool: {function_name}"}
            else:
                # Use the scenario provided by our application,
                # not an untrusted argument generated by the model.
                result = TOOLS[function_name](scenario)
                executed_tools.append(function_name)

            messages.append({
                "role": "tool",
                "tool_name": function_name,
                "content": json.dumps(result),
            })

    return {
        "scenario": scenario,
        "tools_used": executed_tools,
        "report": "Investigation stopped: maximum tool-calling rounds reached.",
    }